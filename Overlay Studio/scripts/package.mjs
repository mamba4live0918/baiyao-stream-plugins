import path from 'node:path';
import fs from 'node:fs/promises';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {Data,NtExecutable,NtExecutableResource,Resource} from 'resedit';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const manifest=JSON.parse(await fs.readFile(path.join(root,'package.json'),'utf8'));
if(!/^\d+\.\d+\.\d+$/.test(manifest.version))throw new Error('Invalid package version');
const require=createRequire(import.meta.url);
const runtime=path.dirname(require('electron'));
const outputName=`Overlay Studio-${manifest.version}-win32-x64`;
const out=path.join(root,'release',outputName);
// Reuse the already installed official runtime: no second archive extractor.
if(path.relative(root,out)!==path.join('release',outputName))throw new Error('Invalid output path');
await fs.access(path.join(root,'dist','index.html'));
if(await fs.lstat(out).then(s=>s.isSymbolicLink(),()=>false))throw new Error('Output cannot be a symlink');
await fs.mkdir(out,{recursive:true});
await fs.cp(runtime,out,{recursive:true});
const target=path.join(out,'resources','app');
await fs.mkdir(target,{recursive:true});
for(const directory of ['dist','electron','resources'])await fs.cp(path.join(root,directory),path.join(target,directory),{recursive:true});
await fs.writeFile(path.join(target,'package.json'),JSON.stringify({name:manifest.name,productName:manifest.productName,version:manifest.version,main:manifest.main,private:true},null,2));
const exePath=path.join(out,'Overlay Studio.exe');
await fs.copyFile(path.join(out,'electron.exe'),exePath);
await fs.unlink(path.join(out,'electron.exe'));
await fs.unlink(path.join(out,'resources','default_app.asar')).catch(e=>{if(e.code!=='ENOENT')throw e;});
const exe=NtExecutable.from(await fs.readFile(exePath)),resources=NtExecutableResource.from(exe);
const group=Resource.IconGroupEntry.fromEntries(resources.entries)[0];
const icon=Data.IconFile.from(await fs.readFile(path.join(root,'resources','icon.ico')));
Resource.IconGroupEntry.replaceIconsForResource(resources.entries,group.id,group.lang,icon.icons.map(x=>x.data));
const version=Resource.VersionInfo.fromEntries(resources.entries)[0];
const versionParts=manifest.version.split('.').map(Number);
version.setFileVersion(...versionParts,0);version.setProductVersion(...versionParts,0);
version.setStringValues(version.getAllLanguagesForStringValues()[0],{CompanyName:'Overlay Studio',FileDescription:'直播小游戏工作台',InternalName:'OverlayStudio',OriginalFilename:'Overlay Studio.exe',ProductName:'Overlay Studio',ProductVersion:manifest.version,FileVersion:manifest.version});
version.outputToResourceEntries(resources.entries);resources.outputResource(exe);
await fs.writeFile(exePath,Buffer.from(exe.generate()));
await fs.copyFile(path.join(root,'使用说明.txt'),path.join(out,'使用说明.txt'));
console.log('Portable Windows app: '+out);
