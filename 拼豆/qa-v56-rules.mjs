// V5.6 浏览器回归：动态互动级别在真实单 HTML 页面中可编辑、预览、刷新与删除。
import assert from 'node:assert/strict';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {chromium} from 'playwright';

const args=['--enable-webgl','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'];
const htmlPath=process.argv[2]?resolve(process.argv[2]):resolve(import.meta.dirname,'拼豆-1.html');
let browser;try{browser=await chromium.launch({channel:'chrome',headless:true,args});}catch{browser=await chromium.launch({headless:true,args});}
const context=await browser.newContext({viewport:{width:1280,height:800}});
await context.routeWebSocket('**/*',ws=>ws.close());
await context.addInitScript(()=>{window.SonglanPlugin={onGift(cb){window.__sendGift=cb;return()=>{};}};});
const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));page.setDefaultTimeout(60000);
const menu=async()=>{await page.mouse.dblclick(25,30);await page.locator('#settings-overlay.open').waitFor();await page.locator('[data-menu-tab="effects"]').click();};
try{
 await page.goto(pathToFileURL(htmlPath).href+'?qa=1');
 await page.waitForFunction(()=>window.__pegQa?.snapshot());
 await menu();
 await page.locator('[data-effect="spill"]').click();
 assert.equal(await page.locator('#rules [data-param="amount"]').count(),0,'打翻托盘是一次性效果，不展示无效的次数参数');
 assert.equal(await page.locator('#rules [data-param="presses"]').count(),1);
 assert.equal(await page.locator('#rules [data-param="decay"]').count(),1);
 await page.locator('[data-effect="help"]').click();
 const before=await page.locator('#rules .tier-card').count();
 await page.locator('#add-interaction-level').click();
 assert.equal(await page.locator('#rules .tier-card').count(),before+1,'点击添加后出现一条可编辑级别');
 const card=page.locator('#rules .tier-card').last();
 const id=await card.getAttribute('data-tier');assert.ok(id);
 await card.locator('[data-param="name"]').fill('观众帮拼');await card.locator('[data-param="name"]').press('Tab');
 await card.locator('[data-param="giftName"]').fill('验收帮拼礼物');await card.locator('[data-param="giftName"]').press('Tab');
 await card.locator('[data-param="amount"]').fill('6');await card.locator('[data-param="amount"]').press('Tab');
 await card.locator('input[type="checkbox"]').check();
 assert.equal(await card.locator('[data-param="name"]').inputValue(),'观众帮拼');
 await page.screenshot({path:resolve(import.meta.dirname,'tmp/qa-v56-rules.png')});
 await page.setViewportSize({width:760,height:800});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'窄窗口没有横向溢出');
 await page.screenshot({path:resolve(import.meta.dirname,'tmp/qa-v56-rules-narrow.png')});
 await page.setViewportSize({width:1280,height:800});
 await card.getByRole('button',{name:'预览此级别'}).click();
 await page.locator('#settings-overlay').waitFor({state:'hidden',timeout:5000});
 await page.waitForFunction(()=>window.__pegQa.snapshot().placed.filter(Boolean).length>=6);
 const afterPreview=await page.evaluate(()=>window.__pegQa.snapshot().placed.filter(Boolean).length);
 await page.evaluate(()=>window.__sendGift({giftName:'验收帮拼礼物',count:2,nickName:'验收'}));
 await page.waitForFunction(n=>window.__pegQa.snapshot().placed.filter(Boolean).length>=n+12,afterPreview);
 await page.evaluate(()=>window.__sendGift({giftName:'再拼一个',count:20,nickName:'验收'}));
 await page.waitForFunction(()=>window.__pegQa.snapshot().requiredRounds===20);
 assert.match(await page.locator('#gift-feed').textContent(),/加了 19 遍/,'播报实际增加的遍数');
 await page.reload();await page.waitForFunction(()=>window.__pegQa?.snapshot());
 await menu();await page.locator('[data-effect="help"]').click();
 const restored=page.locator(`#rules .tier-card[data-tier="${id}"]`);
 assert.equal(await restored.locator('[data-param="name"]').inputValue(),'观众帮拼');
 assert.equal(await restored.locator('[data-param="amount"]').inputValue(),'6');
 await restored.getByRole('button',{name:'删除级别'}).click();
 await page.locator('#confirm-layer:not([hidden])').waitFor();
 await page.locator('#confirm-ok').click();
 await page.locator(`#rules .tier-card[data-tier="${id}"]`).waitFor({state:'detached'});
 assert.deepEqual(errors,[],'页面没有脚本错误');
 const recoveryContext=await browser.newContext({viewport:{width:1280,height:800}});
 await recoveryContext.routeWebSocket('**/*',ws=>ws.close());
 const damaged=JSON.stringify({settings:{rules:[]}});
 await recoveryContext.addInitScript(raw=>localStorage.setItem('songlan-peg-studio-v2',raw),damaged);
 const recoveryPage=await recoveryContext.newPage(),recoveryErrors=[];recoveryPage.on('pageerror',e=>recoveryErrors.push(e.message));
 await recoveryPage.goto(pathToFileURL(htmlPath).href+'?qa=1');
 await recoveryPage.waitForFunction(()=>window.__pegQa?.snapshot());
 assert.equal(await recoveryPage.evaluate(()=>localStorage.getItem('songlan-peg-studio-v2')),damaged,'损坏的原浏览器记录未被静默覆盖');
 assert.match(await recoveryPage.locator('#auto-save-status').textContent(),/未覆盖|临时/);
 await recoveryPage.evaluate(()=>document.querySelector('#settings-button').click());
 await recoveryPage.locator('#settings-overlay.open').waitFor({timeout:5000});
 await recoveryPage.locator('[data-menu-tab="effects"]').click();
 await recoveryPage.locator('#replace-damaged-rules').click();
 await recoveryPage.locator('#confirm-layer:not([hidden])').waitFor();
 await recoveryPage.locator('#confirm-ok').click();
 await recoveryPage.waitForFunction(raw=>localStorage.getItem('songlan-peg-studio-v2')!==raw,damaged);
 assert.equal((await recoveryPage.evaluate(()=>JSON.parse(localStorage.getItem('songlan-peg-studio-v2')).settings.rules)).length,9);
 assert.deepEqual(recoveryErrors,[]);
 await recoveryContext.close();
 const missingContext=await browser.newContext({viewport:{width:1280,height:800}});
 await missingContext.routeWebSocket('**/*',ws=>ws.close());
 const missing=JSON.stringify({settings:{}});
 await missingContext.addInitScript(raw=>localStorage.setItem('songlan-peg-studio-v2',raw),missing);
 const missingPage=await missingContext.newPage();
 await missingPage.goto(pathToFileURL(htmlPath).href+'?qa=1');
 await missingPage.waitForFunction(()=>window.__pegQa?.snapshot());
 assert.equal(await missingPage.evaluate(raw=>localStorage.getItem('songlan-peg-studio-v2')===raw,missing),true,'已有记录缺规则时不能静默覆盖');
 await missingContext.close();
 console.log(JSON.stringify({added:true,previewPlaced:afterPreview,giftTriggered:true,refreshed:true,deleted:true,damagedRulesPreserved:true,missingRulesPreserved:true,pageErrors:errors.length}));
}finally{await browser.close();}
